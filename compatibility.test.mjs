import assert from 'node:assert/strict';
import {evaluateCompatibility,cpuMemoryGenerations} from '../compatibility.js';
import {catalog} from '../catalog.js';
const item=(type,id)=>{const v=catalog[type].find(x=>x.id===id);assert.ok(v,`${type}/${id}`);return v};
const base={case:item('case','c-atx'),board:item('board','h61m-b'),cpu:item('cpu','i7-3770'),ram:item('ram','d3-8'),gpu:item('gpu','rx470'),ssd:item('ssd','sata120'),psu:item('psu','p450'),cooler:null};
const run=(p)=>evaluateCompatibility({...base,...p});
assert.equal(run({}).errors.length,0,'i7-3770/H61/DDR3 should have no known conflict');
assert.ok(run({}).unknown.some(x=>x.includes('BIOS')),'BIOS needs validation');
assert.ok(run({}).warnings.some(x=>x.includes('450 W')),'PSU equality warns');
assert.ok(run({board:item('board','b450'),cpu:item('cpu','i7-3770')}).errors.some(x=>x.includes('sockets')),'socket mismatch');
const xeon=item('cpu','e5-2680v4');
assert.deepEqual(cpuMemoryGenerations(xeon),['DDR4']);
assert.ok(run({cpu:xeon,board:{name:'Placa conceitual',socket:'LGA2011-3',memory:'DDR3'},ram:{name:'DDR3',memory:'DDR3'}}).errors.some(x=>x.includes('Controladora')),'Xeon v4 DDR3 conflict');
const conceptCpu={...xeon,id:'rv42-cpu-001',conceptual:true};
assert.equal(cpuMemoryGenerations(conceptCpu),null,'concept CPU must not imply validated controller');
assert.ok(run({cpu:conceptCpu}).unknown.some(x=>x.includes('Controladora')));
assert.ok(run({gpu:item('gpu','igpu'),cpu:xeon}).errors.some(x=>x.includes('vídeo integrado')));
assert.ok(run({case:{name:'ITX',form:'ITX',gpuMaxMm:150}}).errors.some(x=>x.includes('não cabe')));
assert.ok(run({case:{name:'ATX',form:'ATX',gpuMaxMm:150}}).errors.some(x=>x.includes('excede limite')));
assert.ok(run({psu:{name:'Fonte desconhecida'}}).unknown.some(x=>x.includes('Potência nominal')));
assert.ok(run({ssd:{name:'SSD NVMe',desc:'NVMe'},board:{name:'Board',socket:'LGA1155',memory:'DDR3',form:'mATX',m2Nvme:false}}).unknown.some(x=>x.includes('adaptador')));
assert.equal(run({cooler:null}).complete,false);
const conceptBoards=catalog.board.filter(x=>x.conceptual);
assert.ok(conceptBoards.filter(x=>x.socket==='LGA2011-3').every(x=>x.memory==='DDR4'));
assert.ok(conceptBoards.filter(x=>x.socket==='LGA1155').every(x=>x.memory==='DDR3'));
console.log('PASS: 14 testes de regressão de compatibilidade e catálogo');
