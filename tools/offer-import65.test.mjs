import assert from 'node:assert/strict';
import {stageBotOffers} from '../offer-import65.mjs';
import {auditOffer} from '../offer-policy.mjs';
const item={partId:'5600g',category:'cpu',title:'AMD Ryzen 5 5600G',modelName:'Ryzen 5 5600G',store:'shopee',url:'https://shopee.com.br/example',price:700,checkedAt:'2026-11-15',condition:'new',affiliate:true,affiliateStatus:'confirmed',reviewStatus:'approved'};
const base={schemaVersion:3,offers:[item],history:[]};
const opts={now:new Date('2026-11-15T12:00:00Z')};
const same=stageBotOffers(base,{offers:[{...item}]},opts);
assert.equal(same.unchanged,1);assert.equal(same.document.offers[0].reviewStatus,'approved');
const upd=stageBotOffers(base,{offers:[{...item,price:650}]},opts);
assert.equal(upd.updated,1);assert.equal(upd.document.history.length,1);
assert.equal(upd.document.offers[0].reviewStatus,'pending');
assert.equal(upd.document.offers[0].affiliateStatus,'pending');
assert.equal(auditOffer(upd.document.offers[0],opts.now).displayable,false);
const moved=stageBotOffers(base,{offers:[{...item,url:'https://shopee.com.br/new-link'}]},opts);
assert.equal(moved.updated,1);assert.equal(moved.document.offers.length,1);
const add=stageBotOffers(base,{offers:[{...item,store:'mercadolivre',url:'https://mercadolivre.com.br/item',affiliate:false}]},opts);
assert.equal(add.inserted,1);assert.equal(add.document.offers[1].affiliate,false);
const invalid=stageBotOffers(base,{offers:[{...item,url:'https://evil.example/a'}, {...item,price:-2}]},opts);
assert.equal(invalid.rejected,2);assert.equal(invalid.document.offers.length,1);
assert.equal(base.offers[0].reviewStatus,'approved');
const old=stageBotOffers(base,{offers:[{...item,price:500,checkedAt:'2026-11-14'}]},opts);
assert.equal(old.unchanged,1);
console.log('PASS: importação segura 6.5 (13 cenários)');
